"""Scoped (patch) build support for :class:`GraphBuilder`.

A full ``build()`` re-resolves every file's imports, calls and heritage, which
is the repo-proportional cost of every update. When an edit left a file's
cross-file surface unchanged, nothing outside that file can resolve differently,
so the other files' edges can be reused: the graph is seeded with the persisted
edges and ``build(scope=...)`` re-resolves only the edited files.

Only edge types owned by the per-file import, call and heritage loops are
seeded. Everything a global pass derives (type use, dispatch, same-package,
framework and dynamic edges) is regenerated by that pass exactly as in a full
build, so the patched graph differs from a full rebuild only through the files
in scope.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from typing import Any

# Edge types the heavy per-file loops produce and a patch can therefore reuse.
SEEDED_EDGE_TYPES = frozenset({"imports", "calls", "references", "extends", "implements"})

# Structural edges ``add_file`` creates; a rebuild never touches them.
_STRUCTURAL_EDGE_TYPES = frozenset({"defines", "has_method"})


def edge_attrs_from_row(edge: Mapping[str, Any]) -> dict[str, Any]:
    """In-memory edge attributes for one persisted ``graph_edges`` row."""
    attrs: dict[str, Any] = {
        "edge_type": edge.get("edge_type", "imports"),
        "confidence": edge.get("confidence", 1.0),
    }
    imported_names = edge.get("imported_names")
    if imported_names:
        attrs["imported_names"] = list(imported_names)
    for key in ("hint_source", "resolution_origin"):
        if edge.get(key):
            attrs[key] = edge[key]
    call_lines = edge.get("call_lines")
    if call_lines:
        attrs["call_lines"] = list(call_lines)
    supplied_props = edge.get("supplied_props")
    if supplied_props is not None:
        attrs["supplied_props"] = frozenset(supplied_props)
    for key in ("type_only", "deferred"):
        if edge.get(key):
            attrs[key] = True
    return attrs


class ScopedBuildMixin:
    """Seed a graph with reusable edges and walk only the files in scope."""

    def _scoped_items(self, scope: frozenset[str] | None) -> list[tuple[str, Any]]:
        """``(path, parsed)`` pairs to resolve, in insertion order like a full build."""
        parsed_files = self._parsed_files  # type: ignore[attr-defined]
        if scope is None:
            return list(parsed_files.items())
        return [(p, pf) for p, pf in parsed_files.items() if p in scope]

    def seed_resolved_edges(self, edges: Iterable[Mapping[str, Any]]) -> int:
        """Add persisted edges of the seeded types; returns how many were added.

        Call after every file is added and before ``build(scope=...)``. Edges
        of other types are skipped: a global pass regenerates them.
        """
        graph = self._graph  # type: ignore[attr-defined]
        added = 0
        for edge in edges:
            if edge.get("edge_type") not in SEEDED_EDGE_TYPES:
                continue
            source, target = edge.get("source_node_id"), edge.get("target_node_id")
            if source is None or target is None:
                continue
            graph.add_edge(source, target, **edge_attrs_from_row(edge))
            added += 1
        return added

    def _clear_scope_edges(self, scope: frozenset[str]) -> None:
        """Drop the resolved edges leaving the files in *scope* and their symbols."""
        graph = self._graph  # type: ignore[attr-defined]
        parsed_files = self._parsed_files  # type: ignore[attr-defined]
        owned: set[str] = set()
        for path in scope:
            parsed = parsed_files.get(path)
            if parsed is None:
                continue
            owned.add(path)
            owned.update(sym.id for sym in parsed.symbols)
        stale = [
            (node, target)
            for node in owned
            if node in graph
            for target, data in graph[node].items()
            if data.get("edge_type") not in _STRUCTURAL_EDGE_TYPES
        ]
        graph.remove_edges_from(stale)

    def _seed_import_targets(self, import_targets: dict[str, set[str]], scope: frozenset[str]) -> None:
        """Fill the import sets of files outside *scope* from their seeded edges."""
        graph = self._graph  # type: ignore[attr-defined]
        for path in self._parsed_files:  # type: ignore[attr-defined]
            if path in scope:
                continue
            import_targets[path] = {
                target
                for target, data in graph[path].items()
                if data.get("edge_type") == "imports"
            }
